CREATE TRIGGER AFTERINSERT_NHANVIEN
ON NHANVIEN
AFTER INSERT
AS 
BEGIN
	DECLARE @SONAM INT, @SONU INT;

	SELECT @SONAM = COUNT(*) FROM NHANVIEN WHERE LTRIM(RTRIM(LOWER(GIOITINH))) COLLATE Vietnamese_CI_AI = N'nam';
	SELECT @SONU = COUNT (*) FROM NHANVIEN WHERE LTRIM(RTRIM(LOWER(GIOITINH))) COLLATE Vietnamese_CI_AI = N'nữ';

	PRINT N'Tổng số nhân viên Nam: ' + CAST ( @SONAM AS VARCHAR);
	PRINT N'Tổng số nhân viên Nữ: ' + CAST (@SONU AS VARCHAR);
END

