CREATE TRIGGER NHANVIEN_INSERT_CHECK
ON NHANVIEN
AFTER INSERT
AS
BEGIN
	IF EXISTS (SELECT 1 FROM INSERTED WHERE LUONG <= 15000)
	 BEGIN
        RAISERROR (N'Lương phải lớn hơn 15000', 16, 1)
        ROLLBACK TRANSACTION
        RETURN
    END

	IF EXISTS (SELECT 1 FROM INSERTED WHERE TUOI <18 OR TUOI >65)
	BEGIN 
		RAISERROR (N'Tuổi phải từ 18 đến 65', 16, 1)
		ROLLBACK TRANSACTION 
		RETURN 
	END
END


CREATE TRIGGER NHANVIEN_UPDATE_CHECK
ON NHANVIEN
AFTER UPDATE
AS
BEGIN
	IF EXISTS (SELECT 1 FROM INSERTED WHERE DIACHI LIKE N'%TP HCM%')
	BEGIN
		RAISERROR (N'Không được cập nhật nhân viên ở TP HCM', 16, 1)
		ROLLBACK TRANSACTION
		RETURN 
	END
END

