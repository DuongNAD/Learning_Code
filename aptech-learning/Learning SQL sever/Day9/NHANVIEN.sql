CREATE TABLE NHANVIEN(
	MA_NHANVIEN VARCHAR(5) NOT NULL,
	HO_NHANVIEN NVARCHAR(20) NOT NULL,
	TEN_NHANVIEN NVARCHAR(20) NOT NULL,
	GIOITINH NVARCHAR(3) NOT NULL,
	TUOI INT NOT NULL,
	DIACHI NVARCHAR(50) NOT NULL,
	TONGSO_DA INT NOT NULL
)
